#!/usr/bin/env node
// Builds the redirect system (Phase 3, Task 6) from infra/redirects.json,
// the single source of truth for the Phase 2 migration plan's 301 map:
//
//   - vercel.json gets a "redirects" array using an explicit
//     "statusCode": 301 (not Vercel's "permanent": true shorthand, which
//     issues a 308 — semantically equivalent for SEO but not the literal
//     301 this migration plan calls for throughout) plus
//     "trailingSlash": true, so a request for /about-us (no slash) 301s
//     to /about-us/ automatically — no manual rule needed per page, and
//     both slash forms behave consistently.
//   - infra/cloudfront-function.js gets the equivalent logic for the AWS
//     path: the same redirect map, plus the index.html rewrite every
//     OAC-origin S3 site needs for clean directory URLs to resolve at
//     all (CloudFront's S3 REST origin has no built-in index-document
//     support, unlike the separate "S3 static website hosting" feature).
//
// Also verifies every redirect destination is a real page in site/, so a
// typo in redirects.json fails this script instead of silently 404ing in
// production.
//
// Run once (or after editing infra/redirects.json): `node scripts/gen-redirects.js`.

"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SITE_DIR = path.join(ROOT, "site");
const { redirects } = require(path.join(ROOT, "infra", "redirects.json"));

// ---- Verify every destination resolves to a real page ----
let missing = [];
for (const { source, destination } of redirects) {
  const slug = destination.replace(/^\/|\/$/g, "");
  const target = slug === "" ? path.join(SITE_DIR, "index.html") : path.join(SITE_DIR, slug, "index.html");
  if (!fs.existsSync(target)) missing.push(`${source} -> ${destination} (no site/${slug}/index.html)`);
}
if (missing.length) {
  console.error("Redirect destinations that don't exist in site/:\n" + missing.map((m) => "  " + m).join("\n"));
  process.exit(1);
}

// ---- Verify no chains: no source is also used as a destination ----
const sources = new Set(redirects.map((r) => r.source));
const chained = redirects.filter((r) => sources.has(r.destination));
if (chained.length) {
  console.error("Redirect chain detected (destination is itself a redirect source):\n" + chained.map((r) => `  ${r.source} -> ${r.destination}`).join("\n"));
  process.exit(1);
}

// ---- vercel.json ----
const vercelPath = path.join(ROOT, "vercel.json");
const vercelConfig = JSON.parse(fs.readFileSync(vercelPath, "utf8"));
vercelConfig.trailingSlash = true;
vercelConfig.redirects = redirects.map(({ source, destination }) => ({
  source,
  destination,
  statusCode: 301,
}));
fs.writeFileSync(vercelPath, JSON.stringify(vercelConfig, null, 2) + "\n");
console.log(`vercel.json: wrote ${redirects.length} redirects + trailingSlash: true`);

// ---- infra/cloudfront-function.js ----
const mapEntries = redirects.map((r) => `  "${r.source}": "${r.destination}"`).join(",\n");
const cfFunction = `// Auto-generated by scripts/gen-redirects.js from infra/redirects.json.
// Do not edit by hand — edit redirects.json and regenerate.
//
// CloudFront Function (viewer-request event, JS runtime 2.0). Two jobs:
//   1. 301-redirect every retired WordPress URL in REDIRECTS to its final
//      page (Phase 2 migration plan's one-to-one map — never a blanket
//      redirect to the homepage).
//   2. Rewrite a clean directory URL (e.g. /about-us/) to its index.html
//      object key, and add the trailing slash to a bare page path (e.g.
//      /about-us -> /about-us/) — the S3 REST/OAC origin this site uses
//      has no built-in index-document support, unlike separate "S3
//      static website hosting", so without this every clean URL 404s.
//
// Wire up: associate this function on the DefaultCacheBehavior's
// viewer-request event (see infra/template.yaml).

var REDIRECTS = {
${mapEntries}
};

function handler(event) {
  var request = event.request;
  var uri = request.uri;

  if (REDIRECTS[uri]) {
    return {
      statusCode: 301,
      statusDescription: "Moved Permanently",
      headers: { location: { value: REDIRECTS[uri] } },
    };
  }

  // Bare page path with no trailing slash and no file extension -> add
  // the slash (keeps trailing-slash behaviour identical to the Vercel
  // path's "trailingSlash": true). If the slash-added form is itself a
  // redirect source, send straight to its final destination instead —
  // otherwise a no-slash request for a retired URL would take two hops
  // (add slash, then redirect) rather than one.
  if (uri !== "/" && uri.slice(-1) !== "/" && uri.indexOf(".") === -1) {
    var withSlash = uri + "/";
    return {
      statusCode: 301,
      statusDescription: "Moved Permanently",
      headers: { location: { value: REDIRECTS[withSlash] || withSlash } },
    };
  }

  // Clean directory URL -> its index.html object key.
  if (uri.slice(-1) === "/") {
    request.uri = uri + "index.html";
  }

  return request;
}
`;
fs.writeFileSync(path.join(ROOT, "infra", "cloudfront-function.js"), cfFunction);
console.log(`infra/cloudfront-function.js: wrote ${redirects.length} redirects + index.html/trailing-slash rewrite`);

// ---- inject the same code into infra/template.yaml between the markers ----
const templatePath = path.join(ROOT, "infra", "template.yaml");
const templateSrc = fs.readFileSync(templatePath, "utf8");
const BEGIN = "// BEGIN GENERATED — see infra/cloudfront-function.js / scripts/gen-redirects.js";
const END = "// END GENERATED";
const markerRe = new RegExp(
  `( {8})${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`
);
if (!markerRe.test(templateSrc)) {
  console.error("infra/template.yaml: GENERATED markers not found — is the RedirectsFunction resource still there?");
  process.exit(1);
}
const indentedCode = cfFunction
  .trimEnd()
  .split("\n")
  .map((l) => "        " + l)
  .join("\n");
const replacement = `        ${BEGIN}\n${indentedCode}\n        ${END}`;
fs.writeFileSync(templatePath, templateSrc.replace(markerRe, replacement));
console.log(`infra/template.yaml: injected the same ${redirects.length}-entry function into RedirectsFunction`);

console.log(`\n${redirects.length} redirects verified: every destination exists in site/, no chains detected.`);
